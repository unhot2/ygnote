/** 무기 이미지 경로. 없으면 같은 이름의 기반 일반 무기 이미지를 쓴다 */
export function weaponImagePath(item: WeaponItem | undefined): string | undefined {
  if (!item) return undefined;
  const own = WEAPON_IMAGES[item.id];
  if (own || !item.base) return own;
  const base = WEAPON_ITEMS.find((w) => w.kind === "normal" && w.name === item.base);
  return base ? WEAPON_IMAGES[base.id] : undefined;
}

export function weaponImageById(id: string): string | undefined {
  return weaponImagePath(findWeapon(id));
}
